"""regression_summary.py - per-bug regression evidence from an actual run (SYNTHETIC data).

For every planted bug, switches ONLY that bug on in old_reference.py and runs every
regression check. Writes results/regression_summary.csv and results/regression_summary.md.

    python regression_summary.py
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "tests"))

import fixed  # noqa: E402
import old_reference as old  # noqa: E402
from regression_checks import CHECKS  # noqa: E402
from regression_guards import GUARDS  # noqa: E402


def bug_descriptions():
    out = {}
    for line in open(os.path.join(HERE, "BUGS.md"), encoding="utf-8"):
        m = re.match(r"\| (BUG-\d\d) \| ([^|]+) \| ([^|]+) \|", line)
        if m:
            out[m.group(1)] = (m.group(2).strip(), m.group(3).strip())
    return out


def main(out_dir=os.path.join(HERE, "results")):
    os.makedirs(out_dir, exist_ok=True)
    desc = bug_descriptions()
    fixed_ok = {c.test_name: c.evaluate(fixed)[2] for c in CHECKS}
    all_ok = {c.test_name: c.evaluate(old)[2] for c in CHECKS}
    with old.only_bugs(set()):
        none_ok = {c.test_name: c.evaluate(old)[2] for c in CHECKS}
    rows = []
    for b in sorted(old.ALL_BUGS):
        with old.only_bugs({b}):
            fails = [c for c in CHECKS if not c.evaluate(old)[2]]
        own = [c for c in CHECKS if b in c.bugs]
        own_fail = [c for c in own if c in fails]
        rows.append({
            "bug": b, "area": desc.get(b, ("", ""))[0], "description": desc.get(b, ("", ""))[1],
            "regression_tests": "; ".join(f"{c.tc_id} {c.test_name}" for c in own),
            "own_tests_failing_with_only_this_bug": f"{len(own_fail)}/{len(own)}",
            "other_tests_also_failing": "; ".join(c.tc_id for c in fails if c not in own),
            "own_tests_failing_with_all_bugs": f"{sum(not all_ok[c.test_name] for c in own)}/{len(own)}",
            "own_tests_passing_on_fixed": f"{sum(fixed_ok[c.test_name] for c in own)}/{len(own)}",
            "caught": "YES" if own_fail and all(fixed_ok[c.test_name] for c in own) else "NO",
        })
    with open(os.path.join(out_dir, "regression_summary.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    n_caught = sum(r["caught"] == "YES" for r in rows)
    lines = ["# Regression summary (generated by regression_summary.py from an actual run; SYNTHETIC data)", "",
             f"- Bugs caught by their own regression test with only that bug switched on: **{n_caught}/{len(rows)}**",
             f"- Regression checks failing on old_reference.py (all bugs on): "
             f"**{sum(not v for v in all_ok.values())}/{len(CHECKS)}**",
             f"- Regression checks passing on fixed.py: **{sum(fixed_ok.values())}/{len(CHECKS)}**",
             f"- Regression checks passing on old_reference.py with every bug off (baseline): "
             f"**{sum(none_ok.values())}/{len(CHECKS)}**", "",
             "| Bug | Area | Regression test(s) | Own test fails, bug alone | Also fails (bug alone) | Fails, all bugs | Passes on fixed | Caught |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['bug']} | {r['area']} | {r['regression_tests']} | {r['own_tests_failing_with_only_this_bug']} | "
                     f"{r['other_tests_also_failing'] or '-'} | {r['own_tests_failing_with_all_bugs']} | "
                     f"{r['own_tests_passing_on_fixed']} | {r['caught']} |")
    # Regression guards: worst cases that must keep passing on fixed.py; old_reference.py is recorded only.
    grows = []
    for g in GUARDS:
        f_ok = g.evaluate(fixed)[2]
        o_ok = g.evaluate(old)[2]
        grows.append({"tc_id": g.tc_id, "guard": g.test_name, "fixed": "PASS" if f_ok else "FAIL",
                      "old_reference_recorded": "PASS" if o_ok else "FAIL"})
    with open(os.path.join(out_dir, "regression_guards.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(grows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(grows)
    g_fixed_ok = sum(r["fixed"] == "PASS" for r in grows)
    lines += ["", "## Regression guards (worst cases; must pass on fixed.py, old_reference.py recorded only)", "",
              f"- Guards passing on fixed.py: **{g_fixed_ok}/{len(grows)}**",
              f"- Guards passing on old_reference.py (information only): "
              f"**{sum(r['old_reference_recorded'] == 'PASS' for r in grows)}/{len(grows)}**", "",
              "| TC | Guard | fixed.py | old_reference.py (recorded) |", "|---|---|---|---|"]
    lines += [f"| {r['tc_id']} | {r['guard']} | {r['fixed']} | {r['old_reference_recorded']} |" for r in grows]
    with open(os.path.join(out_dir, "regression_summary.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines[:7]))
    print(f"- Regression guards passing on fixed.py: {g_fixed_ok}/{len(grows)}")
    return 0 if n_caught == len(rows) and g_fixed_ok == len(grows) else 1


if __name__ == "__main__":
    sys.exit(main())
